#!/usr/bin/env python3
"""
gen_cublas_domain.py - generate the cuBLAS tracing domain of the NVIDIA backend.

cuBLAS is a regular shared library: like rocBLAS on AMD, its functions are
interposed (LD_PRELOAD wrappers) and timed by "profiled" functions. This script
parses the prototypes of cublas_api.h (CUBLASAPI <ret> CUBLASWINAPI name(...);)
of the CUDA toolkit used for the build and writes, in the same layout as the
code generated by GILDA for the other domains:

  cublas_api_helper.h          ids, names, argument structures
  cublas_profiled_functions.c  i_<fn>(): activity + callbacks + real call
  cublas_wrapper.c             exported <fn>() forwarding to the API table
  cublas_args.h                rprofrep parameter / argument writers
"""
import argparse
import os
import re
import sys

PROTO_RE = re.compile(r"CUBLASAPI\s+(?P<ret>[^;{}()]*?)\s*CUBLASWINAPI\s+(?P<name>\w+)\s*\((?P<params>[^;{}]*?)\)\s*;", re.S)

# Functions that must not be interposed (logging / internal or with a calling
# convention that cannot be forwarded).
SKIP = {"cublasLoggerConfigure", "cublasSetLoggerCallback", "cublasGetLoggerCallback"}


# cublas_api.h declares the FP16/BF16 functions for C++ only (__half and
# __nv_bfloat16 are C++ classes). The generated code is C: alias them on their
# raw structures (same size and layout) so that every prototype can be traced.
C_COMPAT = """#include <cuda_fp16.h>
#include <cuda_bf16.h>
#ifndef __cplusplus
typedef __half_raw __half;
typedef __nv_bfloat16_raw __nv_bfloat16;
#endif"""


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    return text


def norm(t):
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"\s*\*\s*", " * ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t.replace("* *", "**").replace(" * *", " **")


def parse_param(p, idx):
    p = norm(p)
    if p in ("", "void"):
        return None
    arr = False
    m = re.match(r"(.*?)(\w+)\s*\[\s*\]$", p)
    if m:
        typ, name, arr = m.group(1).strip(), m.group(2), True
    else:
        m = re.match(r"(.*?)(\w+)$", p)
        if not m or not m.group(1).strip():
            return (p, "p%d" % idx, p)
        typ, name = m.group(1).strip(), m.group(2)
    decl_type = typ + (" *" if arr else "")
    decl_type = norm(decl_type)
    # Field type of the argument structure: remove top-level const so that the
    # field can be assigned ('const int n' -> 'int', 'float * const p' -> 'float *').
    field = decl_type
    field = re.sub(r"\*\s*const$", "*", field).strip()
    if "*" not in field:
        field = re.sub(r"^const\s+", "", field).strip()
    return (decl_type, name, field)


STMT_RE = re.compile(r"^(?:CUBLASAPI\s+)?(?P<ret>[\w\s\*]+?)\s*CUBLASWINAPI\s+(?P<name>\w+)\s*\((?P<params>.*)\)\s*$", re.S)


def iter_prototypes(text):
    """Yield the prototype matches of the header (with or without CUBLASAPI,
    CUDA 13 removed it), one C statement at a time."""
    # drop preprocessor lines
    text = "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("#"))
    text = re.sub(r'extern\s+"C"\s*\{', ";", text)
    for stmt in re.split(r"[;{}]", text):
        stmt = stmt.strip()
        if "CUBLASWINAPI" not in stmt:
            continue
        stmt = stmt.replace("CUBLAS_DEPRECATED", "")
        stmt = re.sub(r"__attribute__\s*\(\(.*?\)\)", "", stmt)
        m = STMT_RE.match(stmt)
        if m:
            yield m


def parse_header(path):
    text = strip_comments(open(path, encoding="utf-8", errors="replace").read())
    funcs, seen = [], set()
    for m in iter_prototypes(text):
        name = m.group("name")
        if name in seen or name in SKIP:
            continue
        ret = norm(m.group("ret").replace("CUBLAS_DEPRECATED", ""))
        raw = [x for x in m.group("params").split(",")]
        params, ok = [], True
        for i, p in enumerate(raw):
            r = parse_param(p, i)
            if r is None:
                continue
            if "(" in r[0] or "..." in r[0]:
                ok = False
                break
            params.append(r)
        if not ok:
            continue
        seen.add(name)
        funcs.append((name, ret, params))
    return funcs


def gen_helper(funcs):
    o = ["/* Generated by src/nvidia/gen/gen_cublas_domain.py - DO NOT EDIT. */",
         "#ifndef CUBLAS_API_HELPER_H", "#define CUBLAS_API_HELPER_H", "",
         "#include <string.h>", "#include <stdbool.h>", "#include <stdint.h>",
         "#include <cublas_v2.h> /* defines CUBLASAPI and includes cublas_api.h */", C_COMPAT, "",
         "#ifdef ADD_API_PREFIX", "#undef ADD_API_PREFIX", "#endif",
         "#define ADD_API_PREFIX(str) CUBLAS_API_##str", "",
         "#define FOR_EACH_CUBLAS_FUNC(macro) \\"]
    o += ["macro(%s) \\" % f[0] for f in funcs]
    o += ["", "", "typedef enum {", "    FOR_EACH_CUBLAS_FUNC(GET_FUNC_API_ID)",
          "    CUBLAS_API_ID_NB_FUNCTION,", "    CUBLAS_API_ID_UNKNOWN,", "} cublas_api_id_t;", ""]
    o += ["#include \"cublas_profiled_functions.h\"", ""]
    o += ["static inline const char* get_cublas_funame_by_id(cublas_api_id_t id) {",
          "    switch (id) {", "        FOR_EACH_CUBLAS_FUNC(GET_FUNAME_BY_ID_OF)", "        default: return NULL;", "    }", "}", "",
          "static inline void* get_cublas_funaddr_by_id(cublas_api_id_t id) {",
          "    switch (id) {", "        FOR_EACH_CUBLAS_FUNC(GET_FUNADDR_BY_ID_OF)", "        default: return NULL;", "    }", "}", "",
          "static inline cublas_api_id_t get_cublas_funid_by_name(const char* name) {",
          "    if (name == NULL) return CUBLAS_API_ID_UNKNOWN;",
          "    FOR_EACH_CUBLAS_FUNC(GET_FUNID_BY_NAME_OF)",
          "    return CUBLAS_API_ID_UNKNOWN;", "}", ""]
    for name, ret, params in funcs:
        o.append("typedef struct {")
        for _, pname, field in params:
            o.append("    %s %s;" % (field, pname))
        if ret != "void":
            o.append("    %s retval;" % (re.sub(r"^const\s+", "", ret) if "*" not in ret else ret))
        if not params and ret == "void":
            o.append("    char __unused;")
        o.append("} args_%s_t;" % name)
        o.append("#define GET_ARGS_VALUE_%s(activity) { \\" % name)
        o.append("    args_%s_t* args = (args_%s_t*) activity->args; (void)args; \\" % (name, name))
        for _, pname, field in params:
            o.append("    args->%s = (%s) %s; \\" % (pname, field, pname))
        o.append("};")
        o.append("")
    o += ["#endif /* CUBLAS_API_HELPER_H */"]
    return "\n".join(o) + "\n"


def proto(name, ret, params, prefix="", extra=None):
    ps = ["%s %s" % (t, n) for t, n, _ in params]
    if extra:
        ps.append(extra)
    return "%s %s%s(%s)" % (ret, prefix, name, ", ".join(ps) if ps else "void")


def gen_fun_proto(funcs):
    o = ["/* Generated by src/nvidia/gen/gen_cublas_domain.py - DO NOT EDIT. */",
         "#ifndef CUBLAS_PROFILED_FUNCTIONS_H", "#define CUBLAS_PROFILED_FUNCTIONS_H",
         "#include <cublas_v2.h> /* defines CUBLASAPI and includes cublas_api.h */", C_COMPAT, ""]
    for name, ret, params in funcs:
        o.append(proto(name, ret, params, "i_", "void* return_address") + ";")
        ps = ["%s %s" % (t, n) for t, n, _ in params] + ["void* return_address"]
        o.append("typedef %s (*__%s_t)(%s);" % (ret, name, ", ".join(ps)))
    o.append("#endif")
    return "\n".join(o) + "\n"


def gen_profiled(funcs):
    o = ["/* Generated by src/nvidia/gen/gen_cublas_domain.py - DO NOT EDIT. */",
         "#include <stdlib.h>", "#include \"ratelprof.h\"", "#include \"cublas_api_helper.h\"", "",
         "#define CALL(func, ...) { \\",
         "    __cublas_activity->start_time = ratelprof_get_clock_now(); \\",
         "    ((__##func##_t)cublas_api_table.api_fn[CUBLAS_API_ID_##func])(__VA_ARGS__); \\",
         "    __cublas_activity->stop_time = ratelprof_get_clock_now(); \\", "};", "",
         "#define CALL_RET(ret_type, func, ...) \\",
         "    __cublas_activity->start_time = ratelprof_get_clock_now(); \\",
         "    ret_type __cublas_ret = (ret_type)((__##func##_t)cublas_api_table.api_fn[CUBLAS_API_ID_##func])(__VA_ARGS__); \\",
         "    __cublas_activity->stop_time = ratelprof_get_clock_now(); \\",
         "    ((args_##func##_t*)__cublas_activity->args)->retval = __cublas_ret;", ""]
    for name, ret, params in funcs:
        args = ", ".join([n for _, n, _ in params] + ["NULL"])
        o.append(proto(name, ret, params, "i_", "void* return_address") + " {")
        o.append("    ratelprof_api_activity_t* __cublas_activity = (ratelprof_api_activity_t*)ratelprof_activity_pool_alloc_activity(sizeof(ratelprof_api_activity_t) + sizeof(args_%s_t));" % name)
        o.append("    __cublas_activity->args = (void*)(__cublas_activity + 1);")
        o.append("    __cublas_activity->return_address = return_address;")
        o.append("    ratelprof_on_enter_callbacks[RATELPROF_DOMAIN_CUBLAS](RATELPROF_DOMAIN_CUBLAS, CUBLAS_API_ID_%s, __cublas_activity);" % name)
        if ret == "void":
            o.append("    CALL(%s, %s);" % (name, args))
        else:
            o.append("    CALL_RET(%s, %s, %s);" % (ret, name, args))
        o.append("    GET_ARGS_VALUE_%s(__cublas_activity);" % name)
        o.append("    ratelprof_on_exit_callbacks[RATELPROF_DOMAIN_CUBLAS](RATELPROF_DOMAIN_CUBLAS, CUBLAS_API_ID_%s, __cublas_activity);" % name)
        if ret != "void":
            o.append("    return __cublas_ret;")
        o.append("}")
        o.append("")
    return "\n".join(o) + "\n"


def gen_wrapper(funcs):
    o = ["/* Generated by src/nvidia/gen/gen_cublas_domain.py - DO NOT EDIT. */",
         "#include \"ratelprof.h\"", "#include <cublas_v2.h> /* defines CUBLASAPI and includes cublas_api.h */", C_COMPAT, "",
         "#define CALL(func, ...) ((__##func##_t)RATELPROF_API_PTR(cublas_api_table, CUBLAS_API_ID_##func, #func))(__VA_ARGS__)", ""]
    for name, ret, params in funcs:
        args = ", ".join([n for _, n, _ in params] + ["__builtin_return_address(0)"])
        o.append(proto(name, ret, params) + " {")
        o.append("    %sCALL(%s, %s);" % ("" if ret == "void" else "return ", name, args))
        o.append("}")
        o.append("")
    return "\n".join(o) + "\n"


def c_str(s):
    return '"' + s.replace('"', '\\"') + '"'


def gen_args(funcs):
    o = ["/* Generated by src/nvidia/gen/gen_cublas_domain.py - DO NOT EDIT. */",
         "#ifndef CUBLAS_ARGS_H", "#define CUBLAS_ARGS_H",
         "#include <ratelprof.h>", "#include <ratelprof_ext.h>",
         "#include \"rprofrep_encode_context.h\"", "#include \"utils/rprofrep_msgpack_ext.h\"",
         "#include \"utils/rprofrep_cuda_value.h\"", "#include \"msgpack.h\"", ""]
    for name, ret, params in funcs:
        n = len(params) + (0 if ret == "void" else 1)
        o.append("static void write_%s_params_to_buffer(rprofrep_encode_context_t* ctx, msgpack_buffer_t* buf) {" % name)
        o.append("    msgpack_encode_uint(buf, %d);" % n)
        for t, pn, _ in params:
            o.append("    rprofrep_msgpack_ext_encode_string(ctx, buf, %s);" % c_str(t))
            o.append("    rprofrep_msgpack_ext_encode_string(ctx, buf, %s);" % c_str(pn))
        if ret != "void":
            o.append("    rprofrep_msgpack_ext_encode_string(ctx, buf, %s);" % c_str(ret))
            o.append('    rprofrep_msgpack_ext_encode_string(ctx, buf, "retval");')
        o.append("}")
        o.append("static void write_%s_args_to_buffer(args_%s_t* args, rprofrep_encode_context_t* ctx, msgpack_buffer_t* buf) {" % (name, name))
        o.append("    (void)ctx; (void)args;")
        for _, pn, _ in params:
            o.append("    RP_ENC_VALUE(buf, args->%s);" % pn)
        if ret != "void":
            o.append("    RP_ENC_VALUE(buf, args->retval);")
        o.append("}")
        o.append("")
    o.append("#endif")
    return "\n".join(o) + "\n"


def write(path, content):
    if os.path.exists(path) and open(path, encoding="utf-8").read() == content:
        return
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cuda-include", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    hdr = os.path.join(a.cuda_include, "cublas_api.h")
    if not os.path.exists(hdr):
        print("cublas_api.h not found", file=sys.stderr)
        return 1
    funcs = parse_header(hdr)
    if not funcs:
        print("no cuBLAS prototype found", file=sys.stderr)
        return 1
    os.makedirs(a.out, exist_ok=True)
    write(os.path.join(a.out, "cublas_api_helper.h"), gen_helper(funcs))
    write(os.path.join(a.out, "cublas_profiled_functions.h"), gen_fun_proto(funcs))
    write(os.path.join(a.out, "cublas_profiled_functions.c"), gen_profiled(funcs))
    write(os.path.join(a.out, "cublas_wrapper.c"), gen_wrapper(funcs))
    write(os.path.join(a.out, "cublas_args.h"), gen_args(funcs))
    print("gen_cublas_domain: %d cuBLAS functions" % len(funcs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
