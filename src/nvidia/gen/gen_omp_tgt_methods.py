#!/usr/bin/env python3
"""Generate the adapters hooking libomptarget plugin methods (LLVM >= 19).

Since LLVM 19 the offload plugins are linked into libomptarget.so and the
C entry points __tgt_rtl_<name>(args) became the C++ methods
llvm::omp::target::plugin::GenericPluginTy::<name>(args) (same arguments,
plus `this`). They are reached by direct calls, so they are patched in memory
(see ratelprof_static_hooks.c) and routed to the omp-target domain wrappers
through two adapters per method:

  rp_m_<name>(self, args...)  entered from the patched method: remembers
                              `self` and the trampoline, calls the domain
                              wrapper __tgt_rtl_<name>(args...)
  rp_o_<name>(args...)        installed as the implementation of the domain
                              function: calls the trampoline with `self`

The expected demangled parameter list is emitted so that a method is only
hooked when its signature matches the prototype exactly.
"""
import argparse
import os
import re

PROTO_RE = re.compile(r'^([A-Za-z_][A-Za-z0-9_ \*]*?)\s*(__tgt_rtl_[a-z_]+)\(([^)]*)\)\s*\{', re.M)

# C spelling -> Itanium demangler spelling (LP64)
TYPE_MAP = {
    'int32_t': 'int', 'int': 'int', 'uint32_t': 'unsigned int', 'int64_t': 'long',
    'uint64_t': 'unsigned long', 'ptrdiff_t': 'long', 'size_t': 'unsigned long',
    'bool': 'bool', 'void': 'void',
}


def split_param(p):
    """'const char ** err_str' -> ('const char **', 'err_str')"""
    p = ' '.join(p.replace('*', ' * ').split())
    toks = p.split(' ')
    name = toks[-1]
    ctype = ' '.join(toks[:-1])
    return ctype.replace(' *', '*').replace('* ', '*').strip(), name


def demangled(ctype):
    stars = ctype.count('*')
    base = ctype.replace('*', '').strip()
    const = base.startswith('const ')
    if const:
        base = base[len('const '):].strip()
    base = TYPE_MAP.get(base, base)
    if const:
        base += ' const'
    return base + '*' * stars


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--wrapper', required=True, help='src/wrappers/omp_tgt_rtl_wrapper.c')
    ap.add_argument('--out', required=True)
    args = ap.parse_args()

    src = open(args.wrapper).read()
    protos = []
    for ret, name, params in PROTO_RE.findall(src):
        ret = ' '.join(ret.split()).replace(' *', '*')
        params = params.strip()
        plist = [] if params in ('', 'void') else [split_param(p) for p in params.split(',')]
        protos.append((ret, name, plist))

    out = []
    w = out.append
    w('/* Generated by gen_omp_tgt_methods.py. DO NOT EDIT. */')
    w('#include <stdint.h>')
    w('#include <stddef.h>')
    w('#include "ratelprof.h"')
    w('#include "domains/minimal_abi/omp_tgt_rtl_minimal_abi.h"')
    w('#include "ratelprof/ratelprof_hook.h"')
    w('#include "ratelprof/ratelprof_static_hooks.h"')
    w('')
    for ret, name, plist in protos:
        decl = ', '.join(f'{t} {n}' for t, n in plist) or 'void'
        w(f'{ret} {name}({decl});')
    w('')
    w('#define RP_MSTACK 64')
    w('typedef struct { void* self; void* tramp; } rp_mframe_t;')
    w('static __thread rp_mframe_t rp_mstack[RP_MSTACK];')
    w('static __thread int rp_mtop = 0;')
    w('static inline void rp_mpush(void* self, void* tramp) {')
    w('    if (rp_mtop < RP_MSTACK) { rp_mstack[rp_mtop].self = self; rp_mstack[rp_mtop].tramp = tramp; }')
    w('    rp_mtop++;')
    w('}')
    w('static inline void rp_mpop(void) { rp_mtop--; }')
    w('static inline rp_mframe_t* rp_mcur(void) { return &rp_mstack[(rp_mtop > RP_MSTACK ? RP_MSTACK : rp_mtop) - 1]; }')
    w('')
    entries = []
    for ret, name, plist in protos:
        short = name[len('__tgt_rtl_'):]
        params = ', '.join(f'{t} {n}' for t, n in plist)
        names = ', '.join(n for _, n in plist)
        types = ', '.join(t for t, _ in plist)
        mparams = 'void* self' + (', ' + params if params else '')
        oparams = params or 'void'
        is_void = ret == 'void'
        fnt = f'{ret} (*)(void*{", " + types if types else ""})'
        w(f'static {ret} rp_m_{short}({mparams}) {{')
        w(f'    rp_mpush(self, ratelprof_hook_take());')
        if is_void:
            w(f'    {name}({names});')
            w(f'    rp_mpop();')
        else:
            w(f'    {ret} r = {name}({names});')
            w(f'    rp_mpop();')
            w(f'    return r;')
        w('}')
        w(f'static {ret} rp_o_{short}({oparams}) {{')
        w(f'    rp_mframe_t* f = rp_mcur();')
        call = f'(({fnt})f->tramp)(f->self{", " + names if names else ""})'
        w(f'    {"" if is_void else "return "}{call};')
        w('}')
        w('')
        dm = ', '.join(demangled(t) for t, _ in plist)
        entries.append(f'    {{ "{short}", "{dm}", OMP_TGT_RTL_API_ID_{name}, (void*)rp_m_{short}, (void*)rp_o_{short} }},')
    w('const ratelprof_method_hook_t ratelprof_omp_tgt_rtl_methods[] = {')
    out.extend(entries)
    w('    { NULL, NULL, 0, NULL, NULL }')
    w('};')

    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, 'omp_tgt_rtl_methods.c')
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'gen_omp_tgt_methods: {len(protos)} plugin methods -> {path}')


if __name__ == '__main__':
    main()
